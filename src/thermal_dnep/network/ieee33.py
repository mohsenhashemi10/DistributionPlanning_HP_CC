from pathlib import Path

import pandapower as pp


# ============================================================
# IEEE 33-BUS RADIAL DISTRIBUTION NETWORK
# ============================================================

def create_ieee33_network():

    net = pp.create_empty_network(
        name="IEEE 33-Bus Distribution Network"
    )

    # --------------------------------------------------------
    # Buses
    # --------------------------------------------------------

    buses = []

    for i in range(33):
        bus = pp.create_bus(
            net,
            vn_kv=12.66,
            name=f"Bus {i + 1}",
        )
        buses.append(bus)

    # --------------------------------------------------------
    # External grid
    # --------------------------------------------------------

    pp.create_ext_grid(
        net,
        bus=buses[0],
        vm_pu=1.0,
        name="Grid",
    )

    # --------------------------------------------------------
    # IEEE 33-bus line data
    #
    # From bus | To bus | R (ohm) | X (ohm)
    # --------------------------------------------------------

    line_data = [
        (1, 2, 0.0922, 0.0470),
        (2, 3, 0.4930, 0.2511),
        (3, 4, 0.3660, 0.1864),
        (4, 5, 0.3811, 0.1941),
        (5, 6, 0.8190, 0.7070),
        (6, 7, 0.1872, 0.6188),
        (7, 8, 1.7114, 1.2351),
        (8, 9, 1.0300, 0.7400),
        (9, 10, 1.0400, 0.7400),
        (10, 11, 0.1966, 0.0650),
        (11, 12, 0.3744, 0.1238),
        (12, 13, 1.4680, 1.1550),
        (13, 14, 0.5416, 0.7129),
        (14, 15, 0.5910, 0.5260),
        (15, 16, 0.7463, 0.5450),
        (16, 17, 1.2890, 1.7210),
        (17, 18, 0.7320, 0.5740),
        (2, 19, 0.1640, 0.1565),
        (19, 20, 1.5042, 1.3554),
        (20, 21, 0.4095, 0.4784),
        (21, 22, 0.7089, 0.9373),
        (3, 23, 0.4512, 0.3083),
        (23, 24, 0.8980, 0.7091),
        (24, 25, 0.8960, 0.7011),
        (6, 26, 0.2030, 0.1034),
        (26, 27, 0.2842, 0.1447),
        (27, 28, 1.0590, 0.9337),
        (28, 29, 0.8042, 0.7006),
        (29, 30, 0.5075, 0.2585),
        (30, 31, 0.9744, 0.9630),
        (31, 32, 0.3105, 0.3619),
        (32, 33, 0.3410, 0.5302),
    ]

    # --------------------------------------------------------
    # Line creation
    # --------------------------------------------------------

    for from_bus, to_bus, r_ohm, x_ohm in line_data:

        length_km = 1.0

        r_ohm_per_km = r_ohm
        x_ohm_per_km = x_ohm

        pp.create_line_from_parameters(
            net,
            from_bus=buses[from_bus - 1],
            to_bus=buses[to_bus - 1],
            length_km=length_km,
            r_ohm_per_km=r_ohm_per_km,
            x_ohm_per_km=x_ohm_per_km,
            c_nf_per_km=0.0,
            max_i_ka=1.0,
            name=f"Line {from_bus}-{to_bus}",
        )

    # --------------------------------------------------------
    # IEEE 33-bus load data
    # MW / MVAr
    # --------------------------------------------------------

    load_data = [
        (2, 0.100, 0.060),
        (3, 0.090, 0.040),
        (4, 0.120, 0.080),
        (5, 0.060, 0.030),
        (6, 0.060, 0.020),
        (7, 0.200, 0.100),
        (8, 0.200, 0.100),
        (9, 0.060, 0.020),
        (10, 0.060, 0.020),
        (11, 0.045, 0.030),
        (12, 0.060, 0.035),
        (13, 0.060, 0.035),
        (14, 0.120, 0.080),
        (15, 0.060, 0.010),
        (16, 0.060, 0.020),
        (17, 0.060, 0.020),
        (18, 0.090, 0.040),
        (19, 0.090, 0.040),
        (20, 0.090, 0.040),
        (21, 0.090, 0.040),
        (22, 0.090, 0.040),
        (23, 0.090, 0.050),
        (24, 0.420, 0.200),
        (25, 0.420, 0.200),
        (26, 0.060, 0.025),
        (27, 0.060, 0.025),
        (28, 0.060, 0.020),
        (29, 0.120, 0.070),
        (30, 0.200, 0.600),
        (31, 0.150, 0.070),
        (32, 0.210, 0.100),
        (33, 0.060, 0.040),
    ]

    # --------------------------------------------------------
    # Create loads
    # --------------------------------------------------------

    for bus_no, p_mw, q_mvar in load_data:

        pp.create_load(
            net,
            bus=buses[bus_no - 1],
            p_mw=p_mw,
            q_mvar=q_mvar,
            name=f"Original Load Bus {bus_no}",
        )

    return net


# ============================================================
# TEST
# ============================================================

if __name__ == "__main__":

    net = create_ieee33_network()

    pp.runpp(
        net,
        algorithm="bfsw",
    )

    print(net)
    print("\nBus voltages:")
    print(net.res_bus[["vm_pu", "va_degree"]])

    print("\nLine loading:")
    print(net.res_line[["loading_percent"]])

    print("\nTotal load:")
    print(
        net.load[["p_mw", "q_mvar"]].sum()
    )